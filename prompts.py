from random import choice, randint, sample

from state import RawRecord, PlayerIdentity


# 出题主题域：每次调用随机抽取一个，避免相同 prompt 下模型每次都落回同一个最高频词对（苹果/梨、饺子/馄饨之类）
WORD_TOPICS = [
    "水果蔬菜", "饮品", "主食小吃", "甜品零食", "调味料",
    "哺乳动物", "鸟类", "昆虫", "水生动物", "植物花卉",
    "职业", "体育运动", "乐器", "游戏与玩具", "家用电器",
    "交通工具", "建筑与场所", "文具", "家具", "服饰",
    "美妆护肤", "餐具厨具", "工具", "天气与自然现象",
    "节日与习俗", "城市与地标", "文学与影视角色", "神话与历史人物",
    "情绪与性格", "抽象概念",
]

WORD_FORMS = ["两字词语", "三字词语", "四字成语"]

# 模型默认输出频率最高的一批词对，每次随机抽几个进 prompt 显式排除
OVERTIRED_PAIRS = [
    "苹果/梨", "饺子/馄饨", "包子/馒头", "可乐/雪碧", "咖啡/奶茶",
    "牙刷/牙膏", "洗发水/护发素", "口红/唇膏", "篮球/排球", "老虎/狮子",
    "猫/狗", "沙发/床", "台灯/吊灯", "筷子/叉子", "飞机/高铁",
]


def get_words_prompt():
    topic = choice(WORD_TOPICS)
    form = choice(WORD_FORMS)
    index = randint(2, 9)
    avoid = "、".join(sample(OVERTIRED_PAIRS, k=6))
    return f"""你是“谁是卧底”游戏的出题人，请为主题域「{topic}」构思一对词语（平民词与卧底词），要求：

1. 两个词语都来自「{topic}」，互为同级并列关系，不能是包含关系（如“水果/苹果”这种上下位词，卧底一轮就会暴露）；
2. 都是{form}，且是大众熟知的词，不要生僻词、专业术语或网络新造词；
3. 两个词的差异要微妙：不能在“有无颜色”“冷与热”“甜与咸”“荤与素”“白天与黑夜”“室内与户外”这类非此即彼的显眼属性上形成对立，否则拿卧底词的玩家一句描述就可能暴露身份；差异应藏在质感、语境、使用场景等细节里，需要多轮发言相互印证才能察觉；但也不要近义到变成同一事物的两种叫法，那样完全无从分辨；
4. 禁止输出以下高频词对，也不要输出只与它们差一个字的词对：{avoid}；

请先在脑中构思 10 组不同的候选词对，然后只输出其中的第 {index} 组，通过工具调用返回，不要输出任何其他内容或解释。"""


def get_rules_prompt(player_total: int):
    return f"""你正在参与“谁是卧底”游戏，游戏规则如下：

### 游戏参与方
- {player_total} 个玩家（玩家中包含 1 个卧底，其他玩家均为平民）；
- 每个玩家均不知道自己的身份；
- 每个玩家的名称为：玩家+数字ID，如：玩家 1，玩家 2，...
- 玩家之间互称对方为：玩家ID+号，例如：1号、2号...

### 词语分配
平民获得相同的“平民词”，卧底获得与平民词相关但不同的“卧底词”（如平民词“饺子”，卧底词“馄饨”）。

### 游戏流程
游戏可能有多轮，每一轮包含发言阶段和投票阶段。

#### 发言阶段
每个玩家依次发言，描述自己拿到的词语（不能直接说词语本身）。

#### 投票阶段
每个玩家根据所有发言，投票选出自己怀疑的“卧底”。

### 胜负判断
- 得票最多的玩家被淘汰；
- 若淘汰的是卧底，平民获胜；
- 若淘汰的是平民，游戏继续，进入下一轮；
- 若剩余 1 个平民和 1 个卧底，卧底获胜；

### 游戏技巧
1. 因为玩家不知道自己的身份，有可能自己是平民，也有可能是卧底，所以需要根据各个玩家的发言和投票，来猜测和判断；
2. 在前几轮，最好不要将自己的词语描述的太详细，先试探性地模糊描述，要根据其他玩家的描述情况来揣测自己是不是与众不同的那个（卧底）；
3. 若发现其他玩家有可能和自己是一样的词语（自己有可能是平民），则可以给对方更多的暗示，让对方感受到你和他是一队的（都是平民）；
4. 若发现自己可能和其他玩家的词语都不一样，自己有可能是卧底，那么要将自己伪装成和其他玩家是一样的词语，让他们误投，来争取自己最后的胜利；"""


def get_statement_prompt(player_id: int, your_word: str, history: list[RawRecord]):
    records = [record["content"] for record in history if not record["is_private"] or record["read_only_by"] == player_id]
    return f"""你是玩家 {player_id}，你的词语是“{your_word}”。

以下是游戏中各玩家的发言和投票记录（若记录中还没有玩家发言，表明你是第一个）：

```
{"\n".join(records)}
```

注意：
1. 以上记录中，发言记录是按照玩家的发言顺序从前至后排列；
2. 投票阶段，各玩家同时投票，在投票时，各玩家看不到其他玩家投谁，所以投票记录不分先后顺序；

现在轮到你发言了，请返回以下两个字段：
- thinking：你的内心推理，只有你自己可见，后续轮次也只有你能回看。请结合你的词语和以上记录分析：自己更可能是平民还是卧底、哪些玩家的描述与你的词语兼容、谁最可疑，可以直接提到你的词语；
- content：你的当众发言，所有玩家都能看到。根据 thinking 中的判断来组织——若你可能是卧底，就向平民的描述靠拢伪装自己；若你可能是平民，就与同伴的描述互相印证；不能直接说出词语本身；发言控制在200字以内；不需要做自我介绍；

thinking 和 content 的内容各自保持在一个段落内，不要换行、不要使用列表。通过工具调用返回，不要输出任何其他内容或解释。"""


